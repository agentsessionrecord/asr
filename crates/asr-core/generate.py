#!/usr/bin/env python3
"""Generate Rust field types from the versioned record schema."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'schema/v0/agent-session.schema.json'
TARGET = Path(__file__).parent / 'src/types.rs'
DEFS = json.loads(SOURCE.read_text())['$defs']
STRUCTS = {}


def pascal(name):
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[._]', name))


def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).replace('-', '_').replace('_meta', 'meta').lower()


def nullable(s):
    if '$ref' in s:
        return nullable(DEFS[s['$ref'].split('/')[-1]])
    return not s or 'null' in s.get('type', [])


def typename(s, name):
    if '$ref' in s:
        key = s['$ref'].split('/')[-1]
        return typename(DEFS[key], pascal(key))
    if isinstance(s.get('type'), list) and 'null' in s['type']:
        narrowed = dict(s)
        narrowed['type'] = [t for t in s['type'] if t != 'null']
        return f'Nullable<{typename(narrowed, name)}>'
    if 'const' in s:
        return 'String'
    t = s.get('type')
    if isinstance(t, list):
        t = [k for k in t if k != 'null']
        t = t[0] if len(t) == 1 else None
    if t == 'string':
        return 'String'
    if t in ('number', 'integer'):
        return 'Number'
    if t == 'boolean':
        return 'bool'
    if t == 'array':
        return f'Vec<{typename(s.get("items", {}), name + "Item")}>'
    if t == 'object' and s.get('properties'):
        STRUCTS[name] = s
        return name
    if 'allOf' in s and all('$ref' in x or 'properties' in x for x in s['allOf']):
        combined = {'type': 'object', 'properties': {}, 'required': []}
        for x in s['allOf']:
            x = DEFS[x['$ref'].split('/')[-1]] if '$ref' in x else x
            combined['properties'].update(x.get('properties', {}))
            combined['required'].extend(x.get('required', []))
        return typename(combined, name)
    return 'Value'


def generate():
    lines = ['// Generated by generate.py. Do not edit.',
             '// Schema SHA-256: ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
             'use serde::{Deserialize, Serialize};',
             'use serde_json::{Number, Value};', 'use crate::Nullable;',
             'use std::collections::BTreeMap;', '']
    for key, s in DEFS.items():
        if key.startswith('record.'):
            name = pascal(key.removeprefix('record.'))
            s = DEFS[s['$ref'].split('/')[-1]] if '$ref' in s else s
            merged = dict(s)
            merged['properties'] = {**DEFS['Envelope']['properties'], **s.get('properties', {})}
            merged['required'] = ['type', 'id'] + s.get('required', [])
            STRUCTS[name] = merged
        elif s.get('properties') and key not in ('Envelope',):
            typename(s, pascal(key))
    done = set()
    while done != set(STRUCTS):
        name = next(n for n in STRUCTS if n not in done)
        done.add(name)
        s = STRUCTS[name]
        lines += ['#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]', f'pub struct {name} {{']
        for field, prop in s.get('properties', {}).items():
            ty = typename(prop, name + pascal(field))
            optional = field not in s.get('required', [])
            if optional:
                present = ', deserialize_with = "crate::present"' if nullable(prop) else ''
                lines += [f'    #[serde(default, skip_serializing_if = "Option::is_none"{present})]']
                ty = f'Option<{ty}>'
            ident = 'record_type' if field == 'type' else snake(field)
            if ident in ('ref', 'from', 'mod', 'loop', 'self', 'super', 'move', 'use'):
                ident = 'r#' + ident
            lines += [f'    #[serde(rename = "{field}")]', f'    pub {ident}: {ty},']
        lines += ['    #[serde(flatten)]', '    pub extra: BTreeMap<String, Value>,', '}', '']
    # Open record dispatch preserves future record types and fields.
    lines += ['#[derive(Debug, Clone, PartialEq)]', 'pub enum Record {']
    names = [pascal(k.removeprefix('record.')) for k in DEFS if k.startswith('record.')]
    lines += [f'    {n}({n}),' for n in names] + ['    Unknown(Value),', '}', '']
    lines += ['impl Record {', '    pub fn from_value(value: Value) -> serde_json::Result<Self> {', '        match value["type"].as_str() {']
    for key in DEFS:
        if key.startswith('record.'):
            k = key.removeprefix('record.')
            lines += [f'            Some("{k}") => serde_json::from_value(value).map(Self::{pascal(k)}),']
    lines += ['            _ => Ok(Self::Unknown(value)),', '        }', '    }', '}',
              'impl Serialize for Record {', '    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {', '        match self {']
    lines += [f'            Self::{n}(v) => v.serialize(serializer),' for n in names]
    lines += ['            Self::Unknown(v) => v.serialize(serializer),', '        }', '    }', '}',
              "impl<'de> Deserialize<'de> for Record {", "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {",
              '        Self::from_value(Value::deserialize(deserializer)?).map_err(serde::de::Error::custom)', '    }', '}']
    # Use rustfmt for the committed form. Check mode compares exactly that form.
    import subprocess
    return subprocess.run(['rustfmt', '--edition', '2021'], input='\n'.join(lines)+'\n', text=True, capture_output=True, check=True).stdout


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != result:
            raise SystemExit('Rust schema types are out of date. Run crates/asr-core/generate.py.')
    else:
        TARGET.write_text(result)
