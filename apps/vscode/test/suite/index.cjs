const vscode = require('vscode');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
exports.run = async function () {
  const fixture = JSON.parse(await fs.readFile(process.env.ASR_EDITOR_FIXTURE, 'utf8'));
  const extension = vscode.extensions.getExtension('agentsessionrecord.asr-editor');
  assert.ok(extension); await extension.activate();
  const document = await vscode.workspace.openTextDocument(fixture.file);
  await vscode.window.showTextDocument(document);
  const hovers = await vscode.commands.executeCommand('vscode.executeHoverProvider', document.uri, new vscode.Position(0, 0));
  const text = hovers.flatMap(h => h.contents.map(c => c.value || '')).join('\n').replace(/&nbsp;/g, ' ');
  assert.match(text, /Edited by/); assert.match(text, /Committed by/);
  assert.match(text, /synthetic.served/); assert.match(text, /9007199254740993/);
  assert.match(text, /approvals/); assert.match(text, /not.recorded/);
  const asr = hovers.flatMap(h => h.contents).find(c => c.value?.includes('ASR line evidence'));
  assert.deepEqual(asr.isTrusted, { enabledCommands: ['asr.openSession'] });
  assert.equal(asr.supportHtml, false);
  assert.ok(asr.value.trimStart().startsWith('```text'));
  assert.match(asr.value, /```\s+\[Open session in viewer\]\(command:asr\.openSession\?/);
  const report = await vscode.commands.executeCommand('asr.showLine');
  assert.equal(report.editStatus, 'matched'); assert.equal(report.editedBy.length, 1);
  assert.deepEqual(await vscode.commands.executeCommand('asr.openSession', fixture.reference), { opened: true });
  await vscode.window.showTextDocument(document);
  const edit = new vscode.WorkspaceEdit(); edit.insert(document.uri, new vscode.Position(0, 0), '// unsaved\n');
  await vscode.workspace.applyEdit(edit);
  const dirty = await vscode.commands.executeCommand('vscode.executeHoverProvider', document.uri, new vscode.Position(0, 0));
  assert.ok(dirty.some(h => h.contents.some(c => c.value?.replace(/&nbsp;/g, ' ').includes('Save the file'))));
  await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor');
  console.log('ASR VS Code harness: activation, real blame, exact numbers, safe hover, evidence panel, viewer and dirty-buffer checks passed.');
};
